import puppeteer from 'puppeteer-core';
const BASE = 'https://b3130d50d9af4c448d26f49191e4837f.app.workbuddy.link';
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  ✓', m); } else { fail++; console.log('  ✗', m); } };
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox', '--disable-setuid-sandbox'] });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console.error: ' + m.text()); });
await page.setViewport({ width: 1280, height: 900 });
await page.goto(`${BASE}/?demo=1`, { waitUntil: 'networkidle0' });
await new Promise((r) => setTimeout(r, 1200));
const url = page.url();
ok(url.includes('/t/overview'), `远端 ?demo=1 自动进入工作台 (url=${url})`);
const banner = await page.evaluate(() => document.querySelector('.demo-banner')?.textContent?.trim() ?? '');
ok(banner.includes('只读'), `远端只读横幅可见 ("${banner}")`);
const btns = await page.evaluate(() => Array.from(document.querySelectorAll('button')).map((b) => b.textContent.trim()));
ok(!btns.some((t) => t.includes('新增学员') || t.includes('批量导入') || t.includes('添加教师观察')), '远端：写按钮已隐藏');
const sw = await page.evaluate(async () => { if (!('serviceWorker' in navigator)) return 0; return (await navigator.serviceWorker.getRegistrations()).length; });
ok(sw >= 1, `远端 Service Worker 已注册 (count=${sw})`);
ok(errors.length === 0, `远端无 JS 错误（${errors.length}）`);
if (errors.length) console.log(errors.join('\n'));
await browser.close();
console.log(`\n远端验收：${pass} 通过 / ${fail} 失败`);
process.exit(fail ? 1 : 0);
